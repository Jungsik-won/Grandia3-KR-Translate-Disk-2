FIELDS = [
    "id", "category", "sub_category", "source_file", "inner_file", "record_id",
    "scene_id", "string_index", "original_offset", "pointer_offset", "jp_raw_hex",
    "jp_text", "kr_text", "kr_encoded_hex", "speaker", "control_codes", "status",
    "game_verified", "translator_note", "review_note",
]


def sub_category(category: str) -> str:
    return {
        "1": "weapon", "2": "armor", "3": "shoes", "4": "accessory",
        "5": "mana_egg", "6": "skill_book", "7": "magic", "8": "skill",
        "9": "consumable", "15": "key_item",
    }[category]


def row(item: dict[str, str], kind: str, text: str, value: str) -> dict[str, str]:
    item_id = int(item["item_id"])
    rec = int(item["record_offset"], 16)
    if kind == "NAME":
        offset = item["name_offset"]
        pointer = f"0x{rec + 0x04:06X}"
        raw = item["name_hex"]
        string_index = "0"
        item_id_name = "NAME"
    else:
        offset = item["description_offset"]
        pointer = f"0x{rec + 0x10:06X}"
        raw = item["description_hex"]
        string_index = "1"
        item_id_name = "DESC"
    review = ""
    status = "TRANSLATED"
    if item_id in {225, 445} and kind == "NAME":
        review = "원문 codebook 미해독 토큰을 포함한 이름; 중앙 검토 필요"
        status = "REVIEW_1"
    if item_id == 445 and kind == "NAME":
        review = "원문 65 F6 / 47 F2 미해독. 의미 추정 번역을 사용하지 않고 검토용 표기를 유지함"
        value = "미상 문자 포함 장식품"
    return {
        "id": f"ITEM_{item_id:04d}_{item_id_name}",
        "category": "ITEM",
        "sub_category": sub_category(item["category"]),
        "source_file": "GR3.MDZ",
        "inner_file": "GR3.MDT",
        "record_id": f"ITEM_RECORD_{item_id:04d}",
        "scene_id": "",
        "string_index": string_index,
        "original_offset": offset,
        "pointer_offset": pointer,
        "jp_raw_hex": raw,
        "jp_text": text,
        "kr_text": value,
        "kr_encoded_hex": "UNASSIGNED",
        "speaker": "",
        "control_codes": "[]",
        "status": status,
        "game_verified": "NO",
        "translator_note": "기존 v9 item decode를 재사용; 중앙 hangul_code_map 미배정",
        "review_note": review,
    }


def main() -> None:
    with SOURCE.open(encoding="utf-8-sig", newline="") as handle:
        source_rows = list(csv.DictReader(handle))

    output: list[dict[str, str]] = []
    for item in source_rows:
        item_id = int(item["item_id"])
        if item_id not in NAMES:
            raise SystemExit(f"missing name translation: {item_id}")
        output.append(row(item, "NAME", item["name"], NAMES[item_id]))
        if item["description"]:
            if item_id not in DESCS:
                raise SystemExit(f"missing description translation: {item_id}")
            output.append(row(item, "DESC", item["description"], DESCS[item_id]))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(output)

    glyphs = sorted({char for r in output for char in r["kr_text"] if "\uac00" <= char <= "\ud7a3"})
    GLYPHS.write_text("\n".join(glyphs) + "\n", encoding="utf-8")

    ids = [r["id"] for r in output]
    if len(ids) != len(set(ids)):
        raise SystemExit("duplicate IDs")
    if any(not r["jp_text"] or not r["kr_text"] for r in output):
        raise SystemExit("empty source or translation")
    if len(output) != 822:
        raise SystemExit(f"unexpected row count: {len(output)}")
    print(f"exported {len(output)} rows and {len(glyphs)} unique Hangul syllables")


if __name__ == "__main__":
    main()
