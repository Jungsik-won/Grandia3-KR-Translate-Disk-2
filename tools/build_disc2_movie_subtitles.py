def format_time(seconds: float) -> str:
    millis = round(seconds * 1000)
    hours, millis = divmod(millis, 3_600_000)
    minutes, millis = divmod(millis, 60_000)
    secs, millis = divmod(millis, 1000)
    return f"{hours:02d}:{minutes:02d}:{secs:02d},{millis:03d}"


def wrap_text(text: str, max_chars: int) -> str:
    wrapped: list[str] = []
    for original_line in text.splitlines():
        line = original_line.strip()
        while len(line) > max_chars:
            split = line.rfind(" ", 0, max_chars + 1)
            if split < max_chars // 2:
                split = max_chars
            wrapped.append(line[:split].rstrip())
            line = line[split:].lstrip()
        if line:
            wrapped.append(line)
    return "\n".join(wrapped)


def write_srt(path: Path, cues: list[tuple[float, float, str, str]], language_index: int) -> None:
    blocks = []
    for index, cue in enumerate(cues, start=1):
        text = wrap_text(cue[language_index], 30 if language_index == 2 else 26)
        blocks.append(
            f"{index}\n{format_time(cue[0])} --> {format_time(cue[1])}\n{text}"
        )
    path.write_text("\ufeff" + "\n\n".join(blocks) + "\n", encoding="utf-8")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(8 * 1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def parse_grm50(source: Path) -> list[tuple[float, float, str, str]]:
    import re

    text = source.read_text(encoding="utf-8-sig")
    cues = []
    for block in re.split(r"\n\s*\n", text.strip()):
        lines = block.splitlines()
        if len(lines) < 4:
            raise ValueError(f"Malformed GRM50 reuse cue: {block!r}")
        timing = lines[1]
        start_text, end_text = timing.split(" --> ")
        def seconds(value: str) -> float:
            hours, minutes, tail = value.replace(",", ".").split(":")
            return int(hours) * 3600 + int(minutes) * 60 + float(tail)
        cues.append((seconds(start_text), seconds(end_text), lines[2].rstrip(), "\n".join(lines[3:])))
    return cues


def validate(cues: list[tuple[float, float, str, str]], duration: float, movie_id: str) -> None:
    previous_end = 0.0
    for index, (start, end, ja, ko) in enumerate(cues, start=1):
        if not (0 <= start < end <= duration + 0.05):
            raise ValueError(f"{movie_id} cue {index}: invalid range {start}-{end}/{duration}")
        if start < previous_end:
            raise ValueError(f"{movie_id} cue {index}: overlap {start} < {previous_end}")
        if not ja.strip() or not ko.strip():
            raise ValueError(f"{movie_id} cue {index}: empty text")
        previous_end = end


