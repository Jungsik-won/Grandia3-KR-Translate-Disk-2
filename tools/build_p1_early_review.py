def obvious_small_hallucination(text: str) -> bool:
    if "チャンネル登録" in text or "ご視聴ありがとうございました" in text:
        return True
    prompt_names = ("ユウキ", "アルフィナ", "ミランダ", "エメリウス")
    if sum(name in text for name in prompt_names) >= 3 and text.count("、") >= 3:
        return True
    compact = "".join(character for character in text if character.isalnum())
    return len(compact) >= 30 and len(set(compact)) / len(compact) < 0.12


def overlapping_text(
    segments: list[dict], start: float, end: float, *, screen_small: bool = False
) -> str:
    texts = []
    removed = False
    for segment in segments:
        if float(segment["end"]) <= start or float(segment["start"]) >= end:
            continue
        text = " ".join(str(segment.get("text", "")).split())
        if screen_small and obvious_small_hallucination(text):
            removed = True
            continue
        if text and text not in texts:
            texts.append(text)
    if texts:
        return " | ".join(texts)
    return "[SMALL_HALLUCINATION_REMOVED]" if removed else ""


def main() -> int:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    fields = [
        "event_id", "stream_key", "segment_index", "start_seconds", "end_seconds",
        "speaker", "japanese_base", "japanese_small", "japanese_reviewed",
        "japanese_status", "korean_reviewed", "korean_status", "context_note",
        "evidence", "review_notes",
    ]
    rows = []
    for key, (context, cues) in CUES.items():
        base = json.loads((BASE / f"stream_{key:04x}.json").read_text(encoding="utf-8"))
        small = json.loads((SMALL / f"stream_{key:04x}.json").read_text(encoding="utf-8"))
        for index, cue in enumerate(cues):
            start, end, speaker, jp, ko, *extra = cue
            note = extra[0] if extra else ""
            exact_id = ""
            if "scenario_standard exact phrase:" in note:
                exact_id = note.split("scenario_standard exact phrase:", 1)[1].strip()
            japanese_status = (
                "CROSS_MODEL_REVIEW_PENDING_SCENE" if exact_id else "NEEDS_AUDIO_REVIEW"
            )
            evidence = (
                "whisper_base+whisper_small_independent; "
                + (f"scenario_standard_exact={exact_id}" if exact_id else "scenario_standard=NO_EXACT_MATCH")
                + ("; translation.db_category=SCENARIO" if exact_id else "")
                + "; public_english_script=CONTEXT_ONLY"
            )
            rows.append({
                "event_id": base["event_id"],
                "stream_key": f"0x{key:X}",
                "segment_index": index,
                "start_seconds": f"{float(start):.3f}",
                "end_seconds": f"{float(end):.3f}",
                "speaker": speaker,
                "japanese_base": overlapping_text(base["segments"], float(start), float(end)),
                "japanese_small": overlapping_text(
                    small["segments"], float(start), float(end), screen_small=True
                ),
                "japanese_reviewed": jp,
                "japanese_status": japanese_status,
                "korean_reviewed": ko,
                "korean_status": "DRAFT_CONTEXT_REVIEWED",
                "context_note": context + (f"; scenario_standard_id={exact_id}" if exact_id else ""),
                "evidence": evidence,
                "review_notes": note,
            })
    with OUTPUT.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)
    print(f"wrote {len(rows)} reviewed draft rows across {len(CUES)} events: {OUTPUT}")
    return 0


